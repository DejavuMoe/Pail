// version is stamped at release time (internal/buildstamp).
var version = buildstamp.Version()

// appIcon is generated by tools/genicons from assets/brand/pail-icon.svg.
//
//go:embed appicon.png
var appIcon []byte

func main() {
	showVersion := flag.Bool("version", false, "print the version and exit")
	demo := demoFlag()
	cfgDir := flag.String("config-dir", "", "configuration directory (default: the user config directory)")
	theme := flag.String("theme", "", "theme: system, light or dark (default: the saved setting)")
	size := flag.String("size", "1440x900", "initial window size, WIDTHxHEIGHT")
	tool := flag.String("tool", "", "open a tool view at start: sync, cloudfront, rules, mime, multipart, settings")
	smokeExit := flag.Duration("smoke-exit", 0, "close the window after this duration, e.g. 5s")
	smokeShot := flag.String("smoke-screenshot", "", "save a native window PNG before smoke exit")
	startPprof := pprofFlag()
	flag.Parse()
	startPprof()
	if *showVersion {
		fmt.Println("Pail", version)
		return
	}

	opts, err := parseOptions(*theme, *size, *tool)
	if err != nil {
		log.Fatal(err)
	}
	opts.demo = *demo
	// Closing the window can leave Pail running in the tray, so a second launch
	// shows that window instead of opening the same configuration twice. The
	// demo and a --config-dir of its own are separate instances.
	if !*demo && *cfgDir == "" && !mygo.App.RequestSingleInstanceLock() {
		return
	}
	registerFonts()

	var (
		svc      *core.Service
		stopDemo func()
	)
	if *demo {
		if svc, stopDemo, err = startDemo(); err != nil {
			log.Fatalf("demo: %v", err)
		}
	} else if svc, err = core.New(core.Options{ConfigDir: *cfgDir}); err != nil {
		log.Fatalf("open configuration: %v", err)
	}

	a := newApp(svc, opts)
	a.reveal = func(p string) { mygo.Shell.ShowItemInFolder(p) }
	a.openPath = mygo.Shell.OpenPath
	a.keepRunning = mygo.Power.KeepRunning
	a.writeSecret = func(s string) error {
		return mygo.Clipboard.Write(transfer.TextData(s), mygo.ClipboardOptions{Concealed: true})
	}
	a.openURL = mygo.Shell.OpenExternal
	if !*demo {
		// Transfers left unfinished when Pail last quit come back paused.
		if n, err := svc.RestoreTransfers(); err != nil {
			log.Printf("restore transfers: %v", err)
		} else if n > 0 {
			a.toast(locales.TransfersRestored(n))
			a.transfersOpen = true
		}
	}
	a.quit = mygo.App.Quit
	a.upd.relaunch = relaunchForUpdate
	a.themeSet = mygo.Theme.SetSource
	// The language choice ("" follows the system) is read before the first frame.
	a.lang = loadLanguageChoice()
	a.localeSet = mygo.App.SetLocale
	a.langSave = saveLanguageChoice
	// The saved (or --theme) appearance reaches the system before the window
	// exists, so the window buttons start in the right colors.
	a.syncTheme()

	mygo.App.SetVersion(version)
	if !*demo {
		a.checkUpdatesAtStart()
	}

	// Setup links (pail://account?...) open the add-account form. A release
	// build makes itself the handler of the scheme at every start (Windows:
	// the current user's registry; Linux: a desktop entry; macOS: the bundle's
	// Info.plist declares it), so that the handler follows the app when its
	// folder moves. Development builds and separate instances leave the
	// installed one in place.
	var showWindow func()
	if !*demo && *cfgDir == "" && version != "dev" {
		if err := mygo.App.RegisterURLScheme(core.SetupLinkScheme); err != nil {
			log.Printf("register %s: links: %v", core.SetupLinkScheme, err)
		}
	}
	// Registered before Run, so that it also gets the link Pail started with.
	mygo.App.OnOpenURL(func(raw string) {
		if showWindow != nil {
			showWindow()
		}
		a.enqueue(func() { a.openSetupLink(raw) })
	})

	mygo.App.WhenReady(func() {
		if os.Getenv("MYGO_LOCALE") == "" {
			mygo.App.SetLocale(a.lang) // "" follows the system again
		}
		title := func() string {
			if opts.demo {
				return locales.MainTitleDemo()
			}
			return "Pail"
		}
		// The window is made hidden and shows once its first frame is drawn
		// (mygo draws it while hidden): it opens with its content on every
		// platform, without a frame of the bare background.
		wo := windowOptions(title(), opts.width, opts.height, lightTokens, darkTokens, ui.View(a.view))
		wo.Hidden = true
		win := mygo.NewWindow(wo)
		win.OnReadyToShow(win.Show)
		if err := win.SetIcon(appIcon); err != nil {
			log.Printf("window icon: %v", err)
		}
		a.pick = pickPaths(win)
		a.progressSet = win.SetProgressBar
		// Background work queues closures; Window.Update runs the drain on
		// the UI thread. Work queued before the window existed goes now.
		wake := func() { win.Update(a.uiTurn) }
		a.wake.Store(&wake)
		wake()
		redraw := func() { win.Update(func() {}) }
		installMenu(a, runtime.GOOS, mygo.App.SetMenu, redraw)
		tray := installTray(a, win, redraw, a.tray.on)
		// What was set once (the window title, the labels of the macOS menu
		// and of the tray menu) is set again when the language changes.
		mygo.App.OnLocaleChanged(func(string) {
			win.SetTitle(title())
			installMenu(a, runtime.GOOS, mygo.App.SetMenu, redraw)
			tray.relabel()
		})
		// With the tray icon, closing the window hides it: Pail keeps running
		// and its transfers finish. A quit (the tray's Quit Pail, the app's
		// Quit, ⌘Q, logging out) closes it for real.
		quitting := false
		mygo.App.OnBeforeQuit(func(*mygo.QuitEvent) { quitting = true })
		win.OnClose(func(e *mygo.CloseEvent) {
			if a.closeHides() && !quitting {
				e.PreventDefault()
				win.Hide()
			}
		})
		// The Dock icon (macOS) and a second launch bring the window back.
		mygo.App.OnActivate(func(visible bool) {
			if !visible {
				tray.open()
			}
		})
		mygo.App.OnSecondInstance(func([]string, string) { tray.open() })
		showWindow = tray.open
		win.OnClosed(a.stop)
		if *smokeExit > 0 {
			go smoke(a.ctx, win, *smokeExit, *smokeShot)
		}
	})
	if err := mygo.App.Run(); err != nil {
		log.Print(err)
	}

	a.close()
	// The single instance lock is the process's until it exits (mygo
	// v0.10): a launch meanwhile waits, without a word, for this one to
	// end. So the work after the window has gone is bounded: past
	// quitDeadline the process exits all the same and the launch goes on.
	if !finishWithin(quitDeadline, func() {
		if stopDemo != nil {
			stopDemo() // stops the service, the server and removes the temp dir
			return
		}
		// Unfinished transfers are offered again, paused, at the next start.
		if err := svc.SaveTransfers(); err != nil {
			log.Printf("save transfers: %v", err)
		}
		ctx, cancel := context.WithTimeout(context.Background(), shutdownTimeout)
		defer cancel()
		if err := svc.Shutdown(ctx); err != nil {
			log.Printf("shutdown: %v", err)
		}
	}) {
		log.Printf("shutdown did not finish within %v: exiting so that a new Pail can start", quitDeadline)
	}
}

const (
	// shutdownTimeout is how long running transfers have to stop cleanly
	// (abort their multipart uploads, remove their temporary files) as
	// Pail quits.
	shutdownTimeout = 5 * time.Second
	// quitDeadline bounds all the work after the window has gone: the
	// shutdown above, and what does not heed its context (a keychain or
	// vault call that hangs). Until the process exits, a second launch
	// waits for its single instance lock.
	quitDeadline = shutdownTimeout + 3*time.Second
)

// finishWithin runs work and waits for it at most d, reporting whether it
// finished. Work that is still running when it returns goes on until the
// process exits.
func finishWithin(d time.Duration, work func()) bool {
	done := make(chan struct{})
	go func() {
		defer close(done)
		work()
	}()
	t := time.NewTimer(d)
	defer t.Stop()
	select {
	case <-done:
		return true
	case <-t.C:
		return false
	}
}

func parseOptions(theme, size, tool string) (options, error) {
	o := options{theme: theme, tool: tool}
	switch theme {
	case "", "system", "light", "dark":
	default:
		return o, fmt.Errorf("unknown --theme %q (system, light or dark)", theme)
	}
	w, h, ok := strings.Cut(size, "x")
	var err1, err2 error
	o.width, err1 = strconv.Atoi(w)
	o.height, err2 = strconv.Atoi(h)
	if !ok || err1 != nil || err2 != nil || o.width < 640 || o.height < 480 {
		return o, fmt.Errorf("bad --size %q, want WIDTHxHEIGHT such as 1440x900", size)
	}
	if tool != "" {
		if _, known := toolInfo[tool]; !known {
			return o, fmt.Errorf("unknown --tool %q", tool)
		}
	}
	return o, nil
}

// pickPaths opens the native file or folder chooser. It blocks, so callers
// run it on a goroutine.
func pickPaths(win *mygo.Window) func(dir bool) []string {
	return func(dir bool) []string {
		title := locales.MainPickFiles()
		if dir {
			title = locales.MainPickFolder()
		}
		paths, err := mygo.Dialog.Open(mygo.OpenDialogOptions{Parent: win, Title: title, Directory: dir, Multiple: !dir})
		if err != nil {
			log.Printf("file dialog: %v", err)
			return nil
		}
		return paths
	}
}

// smoke closes the window after d, saving a PNG of it first when asked.
func smoke(ctx context.Context, win *mygo.Window, d time.Duration, shot string) {
	t := time.NewTimer(d)
	defer t.Stop()
	select {
	case <-ctx.Done():
		return
	case <-t.C:
	}
	if shot != "" {
		if err := capture(win, shot); err != nil {
			log.Printf("smoke screenshot failed: %v", err)
		} else {
			log.Printf("smoke screenshot saved: %s", shot)
		}
	}
	mygo.App.Quit()
}

func capture(win *mygo.Window, path string) error {
	raw, err := win.CapturePage()
	if err != nil {
		return err
	}
	img, _, err := image.Decode(bytes.NewReader(raw))
	if err != nil {
		return err
	}
	var out bytes.Buffer
	if err := png.Encode(&out, img); err != nil {
		return err
	}
	return os.WriteFile(path, out.Bytes(), 0o600)
}

// relaunchForUpdate quits and starts the updated Pail. On macOS the new app
// bundle replaces the old one only once this process has exited, and the
// helper that does it opens Pail again.
func relaunchForUpdate() {
	if runtime.GOOS == "darwin" && selfupdate.RelaunchAfterExit(nil) {
		mygo.App.Quit()
		return
	}
	mygo.App.Relaunch()
}
